def find_rule(
    stage: str, reserve: str, invasion: str, spread: str, portal_hypertension: str
) -> DecisionRule:
    matches = tuple(
        rule
        for rule in DECISION_RULES
        if rule.stage == stage
        and rule.reserve == reserve
        and rule.invasion == invasion
        and rule.spread == spread
        and rule.portal_hypertension == portal_hypertension
    )
    if len(matches) != 1:
        raise KeyError((stage, reserve, invasion, spread, portal_hypertension))
    return matches[0]


def validate_rulebook() -> None:
    identifiers = {rule.identifier for rule in DECISION_RULES}
    if len(identifiers) != len(DECISION_RULES):
        raise ValueError("duplicate rule identifier")
    if len(DECISION_RULES) != 384:
        raise ValueError("incomplete decision matrix")
